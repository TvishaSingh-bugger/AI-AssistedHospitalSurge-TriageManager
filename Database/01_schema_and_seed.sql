-- ===== CORE SCHEMA AND HOSPITAL SEED DATA (01_schema_and_seed.sql) =====
CREATE DATABASE IF NOT EXISTS hospital_surge_db
  CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
USE hospital_surge_db;

SET FOREIGN_KEY_CHECKS = 0;
DROP TABLE IF EXISTS system_events;
DROP TABLE IF EXISTS resource_history;
DROP TABLE IF EXISTS scheduling_results;
DROP TABLE IF EXISTS scheduling_runs;
DROP TABLE IF EXISTS queue_entries;
DROP TABLE IF EXISTS resource_allocations;
DROP TABLE IF EXISTS case_resource_requirements;
DROP TABLE IF EXISTS resource_inventory;
DROP TABLE IF EXISTS medical_staff;
DROP TABLE IF EXISTS emergency_cases;
DROP TABLE IF EXISTS patients;
DROP TABLE IF EXISTS hospitals;
SET FOREIGN_KEY_CHECKS = 1;

CREATE TABLE hospitals (
  hospital_id INT AUTO_INCREMENT PRIMARY KEY,
  hospital_code VARCHAR(20) NOT NULL UNIQUE,
  hospital_name VARCHAR(150) NOT NULL,
  district VARCHAR(100) NOT NULL,
  state_name VARCHAR(100) NOT NULL DEFAULT 'Uttarakhand',
  hospital_type ENUM('Government','Private','Trust','Other') NOT NULL DEFAULT 'Government',
  total_beds INT NULL DEFAULT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (total_beds >= 0)
);

CREATE TABLE patients (
  patient_id BIGINT AUTO_INCREMENT PRIMARY KEY,
  hospital_id INT NOT NULL,
  patient_code VARCHAR(30) NOT NULL,
  age TINYINT UNSIGNED NULL,
  sex ENUM('Female','Male','Other','Prefer not to say') NULL,
  registered_at DATETIME NOT NULL,
  is_synthetic BOOLEAN NOT NULL DEFAULT TRUE,
  UNIQUE KEY uq_patient_hospital_code (hospital_id, patient_code),
  CONSTRAINT fk_patients_hospital FOREIGN KEY (hospital_id)
    REFERENCES hospitals(hospital_id),
  CHECK (age IS NULL OR age <= 120)
);

CREATE TABLE medical_staff (
  staff_id INT AUTO_INCREMENT PRIMARY KEY,
  hospital_id INT NOT NULL,
  staff_code VARCHAR(30) NOT NULL,
  staff_name VARCHAR(100) NOT NULL,
  role ENUM('Doctor','Nurse','Technician','Paramedic','Other') NOT NULL,
  available_count INT NOT NULL DEFAULT 1,
  shift_start DATETIME NULL,
  shift_end DATETIME NULL,
  UNIQUE KEY uq_staff_hospital_code (hospital_id, staff_code),
  CONSTRAINT fk_staff_hospital FOREIGN KEY (hospital_id)
    REFERENCES hospitals(hospital_id),
  CHECK (available_count >= 0)
);

CREATE TABLE emergency_cases (
  case_id BIGINT AUTO_INCREMENT PRIMARY KEY,
  hospital_id INT NOT NULL,
  patient_id BIGINT NOT NULL,
  case_code VARCHAR(30) NOT NULL,
  case_type VARCHAR(100) NOT NULL,
  triage_level ENUM('Critical','High','Medium','Low') NOT NULL,
  -- Current priority.js selects the LARGEST number first: 5 is highest.
  priority TINYINT UNSIGNED NOT NULL DEFAULT 3,
  arrival_time DATETIME NOT NULL,
  -- Relative simulation time. Use one consistent unit throughout (e.g. minutes).
  arrival_time_units INT UNSIGNED NOT NULL,
  burst_time INT UNSIGNED NOT NULL,
  remaining_time INT UNSIGNED NOT NULL,
  process_state ENUM(
    'NEW','Ready','Running','Waiting','Completed','Cancelled'
  ) NOT NULL DEFAULT 'NEW',
  assigned_staff_id INT NULL,
  notes VARCHAR(500) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_case_hospital_code (hospital_id, case_code),
  KEY idx_cases_hospital_state_arrival (hospital_id, process_state, arrival_time_units),
  KEY idx_cases_priority (hospital_id, priority, arrival_time_units),
  CONSTRAINT fk_cases_hospital FOREIGN KEY (hospital_id)
    REFERENCES hospitals(hospital_id),
  CONSTRAINT fk_cases_patient FOREIGN KEY (patient_id)
    REFERENCES patients(patient_id),
  CONSTRAINT fk_cases_staff FOREIGN KEY (assigned_staff_id)
    REFERENCES medical_staff(staff_id),
  CHECK (priority BETWEEN 1 AND 5),
  CHECK (burst_time > 0),
  CHECK (remaining_time <= burst_time)
);

CREATE TABLE resource_inventory (
  resource_id INT AUTO_INCREMENT PRIMARY KEY,
  hospital_id INT NOT NULL,
  resource_type ENUM(
    'ICU_BED','GENERAL_BED','VENTILATOR',
    'OXYGEN_CYLINDER','OXYGEN_SUPPLY','BLOOD_UNIT'
  ) NOT NULL,
  blood_group ENUM('A+','A-','B+','B-','AB+','AB-','O+','O-') NULL,
  total_quantity INT UNSIGNED NOT NULL DEFAULT 0,
  available_quantity INT UNSIGNED NOT NULL DEFAULT 0,
  unit VARCHAR(30) NOT NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
    ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_inventory_type_group (hospital_id, resource_type, blood_group),
  CONSTRAINT fk_inventory_hospital FOREIGN KEY (hospital_id)
    REFERENCES hospitals(hospital_id),
  CHECK (available_quantity <= total_quantity)
);

CREATE TABLE case_resource_requirements (
  requirement_id BIGINT AUTO_INCREMENT PRIMARY KEY,
  case_id BIGINT NOT NULL,
  resource_type ENUM(
    'ICU_BED','GENERAL_BED','VENTILATOR',
    'OXYGEN_CYLINDER','OXYGEN_SUPPLY','BLOOD_UNIT'
  ) NOT NULL,
  blood_group ENUM('A+','A-','B+','B-','AB+','AB-','O+','O-') NULL,
  required_quantity INT UNSIGNED NOT NULL,
  notes VARCHAR(255) NULL,
  CONSTRAINT fk_requirements_case FOREIGN KEY (case_id)
    REFERENCES emergency_cases(case_id),
  CHECK (required_quantity > 0)
);

CREATE TABLE resource_allocations (
  allocation_id BIGINT AUTO_INCREMENT PRIMARY KEY,
  case_id BIGINT NOT NULL,
  resource_id INT NOT NULL,
  quantity INT UNSIGNED NOT NULL,
  allocated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  released_at DATETIME NULL,
  allocation_status ENUM('Allocated','Released','Cancelled')
    NOT NULL DEFAULT 'Allocated',
  CONSTRAINT fk_allocations_case FOREIGN KEY (case_id)
    REFERENCES emergency_cases(case_id),
  CONSTRAINT fk_allocations_resource FOREIGN KEY (resource_id)
    REFERENCES resource_inventory(resource_id),
  KEY idx_allocation_active (resource_id, allocation_status),
  CHECK (quantity > 0),
  CHECK (released_at IS NULL OR released_at >= allocated_at)
);

-- Durable representation of the in-memory queues in queue.js,
-- producerConsumer.js and resourceWaiting.js.
CREATE TABLE queue_entries (
  queue_entry_id BIGINT AUTO_INCREMENT PRIMARY KEY,
  hospital_id INT NOT NULL,
  case_id BIGINT NOT NULL,
  queue_type ENUM('PRODUCER_BUFFER','READY','RESOURCE_WAITING') NOT NULL,
  queue_position BIGINT UNSIGNED NOT NULL,
  queue_status ENUM('QUEUED','PROCESSING','CONSUMED','REMOVED') NOT NULL DEFAULT 'QUEUED',
  entered_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  removed_at DATETIME NULL,
  KEY idx_queue_case_status (case_id, queue_type, queue_status),
  KEY idx_queue_order (hospital_id, queue_type, queue_status, queue_position),
  CONSTRAINT fk_queue_hospital FOREIGN KEY (hospital_id)
    REFERENCES hospitals(hospital_id),
  CONSTRAINT fk_queue_case FOREIGN KEY (case_id)
    REFERENCES emergency_cases(case_id)
);

CREATE TABLE scheduling_runs (
  run_id BIGINT AUTO_INCREMENT PRIMARY KEY,
  hospital_id INT NOT NULL,
  algorithm ENUM('FCFS','PRIORITY','SJF','ROUND_ROBIN') NOT NULL,
  time_quantum INT UNSIGNED NULL,
  aging_waiting_limit INT UNSIGNED NULL,
  starvation_max_wait INT UNSIGNED NULL,
  simulation_start DATETIME NOT NULL,
  simulation_unit ENUM('SECOND','MINUTE') NOT NULL DEFAULT 'MINUTE',
  run_status ENUM('RUNNING','COMPLETED','FAILED') NOT NULL DEFAULT 'RUNNING',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_runs_hospital FOREIGN KEY (hospital_id)
    REFERENCES hospitals(hospital_id),
  CHECK (algorithm <> 'ROUND_ROBIN' OR time_quantum IS NOT NULL),
  CHECK (time_quantum IS NULL OR time_quantum > 0)
);

CREATE TABLE scheduling_results (
  result_id BIGINT AUTO_INCREMENT PRIMARY KEY,
  run_id BIGINT NOT NULL,
  case_id BIGINT NOT NULL,
  execution_order INT UNSIGNED NOT NULL,
  start_time_units INT UNSIGNED NULL,
  completion_time_units INT UNSIGNED NOT NULL,
  turnaround_time INT UNSIGNED NOT NULL,
  waiting_time INT UNSIGNED NOT NULL,
  response_time INT UNSIGNED NULL,
  priority_at_execution TINYINT UNSIGNED NULL,
  final_state ENUM('Completed','Waiting','Cancelled') NOT NULL DEFAULT 'Completed',
  CONSTRAINT fk_results_run FOREIGN KEY (run_id)
    REFERENCES scheduling_runs(run_id),
  CONSTRAINT fk_results_case FOREIGN KEY (case_id)
    REFERENCES emergency_cases(case_id),
  UNIQUE KEY uq_run_case (run_id, case_id),
  CHECK (waiting_time >= 0),
  CHECK (turnaround_time >= 0)
);

CREATE TABLE resource_history (
  history_id BIGINT AUTO_INCREMENT PRIMARY KEY,
  resource_id INT NOT NULL,
  recorded_at DATETIME NOT NULL,
  total_quantity INT UNSIGNED NOT NULL,
  available_quantity INT UNSIGNED NOT NULL,
  used_quantity INT UNSIGNED NOT NULL,
  source ENUM('MANUAL','ALLOCATION','RELEASE','SYNTHETIC') NOT NULL DEFAULT 'SYNTHETIC',
  CONSTRAINT fk_history_resource FOREIGN KEY (resource_id)
    REFERENCES resource_inventory(resource_id),
  KEY idx_resource_history_time (resource_id, recorded_at),
  CHECK (available_quantity <= total_quantity)
);

CREATE TABLE system_events (
  event_id BIGINT AUTO_INCREMENT PRIMARY KEY,
  hospital_id INT NOT NULL,
  case_id BIGINT NULL,
  event_type ENUM(
    'CASE_QUEUED','CASE_DEQUEUED','AGING_APPLIED',
    'STARVATION_WARNING','RESOURCE_WAIT','RESOURCE_ALLOCATED',
    'RESOURCE_RELEASED','BUFFER_FULL','BUFFER_EMPTY',
    'SCHEDULING_STARTED','SCHEDULING_COMPLETED','ERROR'
  ) NOT NULL,
  event_message VARCHAR(500) NOT NULL,
  event_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  metadata JSON NULL,
  CONSTRAINT fk_events_hospital FOREIGN KEY (hospital_id)
    REFERENCES hospitals(hospital_id),
  CONSTRAINT fk_events_case FOREIGN KEY (case_id)
    REFERENCES emergency_cases(case_id),
  KEY idx_events_hospital_time (hospital_id, event_time)
);

